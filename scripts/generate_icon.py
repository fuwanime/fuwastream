#!/usr/bin/env python3
"""Generate every FuwaStream launcher asset from one geometry definition.

Outputs:
  res/drawable/ic_launcher_foreground.xml   (adaptive foreground, lavender petal-play)
  res/drawable/ic_launcher_monochrome.xml   (themed-icon layer, white)
  res/drawable/ic_launcher_background.xml   (flat ink field)
  res/mipmap-*/ic_launcher.png              (legacy square, 48..192 px)
  res/mipmap-*/ic_launcher_round.png        (legacy round)
"""
from PIL import Image, ImageDraw
import os
import sys

RES = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/res"

INK = (15, 13, 21)      # #0F0D15
LAV = (212, 187, 255)   # #D4BBFF
SS = 4

TIP = (84.0, 54.0)
SEGMENTS = [
    ("M", TIP),
    ("C", (70.0, 34.0), (48.0, 26.0), (34.0, 32.0)),
    ("C", (26.0, 36.0), (24.0, 44.4), (34.0, 47.0)),
    ("L", (50.0, 54.0)),
    ("L", (34.0, 61.0)),
    ("C", (24.0, 63.6), (26.0, 72.0), (34.0, 76.0)),
    ("C", (48.0, 82.0), (70.0, 74.0), TIP),
    ("Z",),
]


def path_data():
    parts = []
    for seg in SEGMENTS:
        name, pts = seg[0], seg[1:]
        if name == "Z":
            parts.append("Z")
        elif name == "M":
            parts.append(f"M{pts[0][0]:g},{pts[0][1]:g}")
        elif name == "L":
            parts.append(f"L{pts[0][0]:g},{pts[0][1]:g}")
        else:
            parts.append("C" + " ".join(f"{x:g},{y:g}" for x, y in pts))
    return " ".join(parts)


def bez(p0, p1, p2, p3, n=40):
    out = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        out.append((
            u**3*p0[0] + 3*u*u*t*p1[0] + 3*u*t*t*p2[0] + t**3*p3[0],
            u**3*p0[1] + 3*u*u*t*p1[1] + 3*u*t*t*p2[1] + t**3*p3[1],
        ))
    return out


def polygon():
    pts, cur = [], None
    for seg in SEGMENTS:
        if seg[0] == "M":
            cur = seg[1]
            pts.append(cur)
        elif seg[0] == "L":
            cur = seg[1]
            pts.append(cur)
        elif seg[0] == "C":
            _, c1, c2, end = seg
            pts += bez(cur, c1, c2, end)[1:]
            cur = end
    return pts


def render(size, round_icon=False, scale=1.0):
    s = size * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_icon:
        d.ellipse((0, 0, s - 1, s - 1), fill=INK + (255,))
    else:
        d.rectangle((0, 0, s, s), fill=INK + (255,))
    k = s / 108
    cx = cy = 54.0
    pts = [((x - cx) * scale + cx, (y - cy) * scale + cy) for x, y in polygon()]
    d.polygon([(x * k, y * k) for x, y in pts], fill=LAV + (255,))
    return img.resize((size, size), Image.LANCZOS)


VECTOR = """<?xml version="1.0" encoding="utf-8"?>
<!-- FuwaStream mark: a sakura petal whose silhouette doubles as a play button.
     Generated by scripts/generate_icon.py - edit the geometry there, not here. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{color}"
        android:pathData="{path}" />
</vector>
"""

BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<shape xmlns:android="http://schemas.android.com/apk/res/android"
    android:shape="rectangle">
    <solid android:color="#0F0D15" />
</shape>
"""

MIPMAPS = {
    "mipmap-mdpi": 48,
    "mipmap-hdpi": 72,
    "mipmap-xhdpi": 96,
    "mipmap-xxhdpi": 144,
    "mipmap-xxxhdpi": 192,
}


def main():
    path = path_data()
    drawable = os.path.join(RES, "drawable")
    os.makedirs(drawable, exist_ok=True)
    with open(os.path.join(drawable, "ic_launcher_foreground.xml"), "w") as f:
        f.write(VECTOR.format(color="#D4BBFF", path=path))
    with open(os.path.join(drawable, "ic_launcher_monochrome.xml"), "w") as f:
        f.write(VECTOR.format(color="#FFFFFF", path=path))
    with open(os.path.join(drawable, "ic_launcher_background.xml"), "w") as f:
        f.write(BACKGROUND)

    for folder, size in MIPMAPS.items():
        d = os.path.join(RES, folder)
        os.makedirs(d, exist_ok=True)
        render(size).save(os.path.join(d, "ic_launcher.png"))
        # The round variant keeps the mark inside the circular crop.
        render(size, round_icon=True, scale=0.78).save(os.path.join(d, "ic_launcher_round.png"))
        print(f"{folder}: {size}px ok")

    # Large previews for the store listing.
    render(512).save("/tmp/store-icon-512.png")
    render(192, round_icon=True, scale=0.78).save("/tmp/adaptive-round-preview.png")
    print("wrote /tmp/store-icon-512.png")
    print("pathData:", path)


if __name__ == "__main__":
    main()
